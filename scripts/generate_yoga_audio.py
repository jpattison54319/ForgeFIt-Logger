#!/usr/bin/env python3
"""Build ForgeFit's offline guided-yoga narration through OpenRouter.

The script deliberately separates four gates:

1. ``catalog`` is free and shows the exact transcript/asset workload.
2. ``audition`` is a small billable run across candidate voices.
3. ``batch`` refuses to run until the chosen female and male voices are
   explicitly marked as audition-approved.
4. ``verify`` checks every expected asset and is the only command that may
   mark the bundled manifest approved.

No pose text is generated by a model. Gemini narrates the reviewed words in
``ForgeFit/Resources/yoga_guidance.json`` exactly as authored.
"""

